/**
 * Статьи — то, ради чего человек приходит из поиска.
 *
 * У сайта есть страницы про форматы, но нет ни одной страницы, которая
 * отвечала бы на вопрос. А ищут именно вопросами: «как перестать всё
 * контролировать», «что такое самадхи простыми словами». Google показывает
 * страницу, а не сайт: нет страницы с ответом — нечего показывать.
 *
 * Каждая статья растёт из ролика на YouTube: расшифровка — сырьё, не текст.
 * Устная речь на странице читается плохо, и поисковик с прошлого года
 * отдельно понижает страницы, сделанные для робота, а не для человека.
 * Поэтому здесь живёт причёсанный текст, а под ним — сам ролик.
 *
 * Пока список пуст, раздела на сайте нет: ни ссылки в шапке, ни адреса в
 * карте сайта. Пустой раздел в индексе хуже, чем никакого.
 */

export type ArticleBlock =
  /** Подзаголовок внутри статьи. */
  | { kind: 'h'; text: string }
  | { kind: 'p'; text: string }
  | { kind: 'li'; text: string }
  /** Выделенная фраза — то, что человек унесёт, даже если прочтёт по диагонали. */
  | { kind: 'quote'; text: string };

export interface Article {
  /** Адрес: /blog/<slug>/. Только латиница, цифры и дефис. */
  slug: string;
  /** Заголовок — так, как человек спрашивает, а не так, как красивее. */
  title: string;
  /** Строка под заголовком в выдаче: 120–160 знаков. */
  description: string;
  /**
   * Ответ на вопрос заголовка, целиком, в одном абзаце.
   *
   * Он стоит до всего остального сознательно: человек пришёл за ответом, а
   * не за подводкой. Кто захочет разобраться — дочитает.
   */
  lead: string;
  /** Идентификатор ролика на YouTube, из которого выросла статья. */
  video?: string;
  /** Дата публикации, `2026-11-24`. */
  date: string;
  /** Дата последней правки, если текст заметно менялся. */
  updated?: string;
  /** К какому формату ведёт статья — спокойной строкой в конце, без нажима. */
  cta?: 'samadhi-club' | 'forever-young' | 'consultation' | 'mentorship';
  blocks: ArticleBlock[];
}

export const articles: Article[] = [];

/** Раздел появляется сам, когда появляется первая статья. */
export const showBlog = articles.length > 0;

/** Свежие сверху: читателю и поисковику интересно новое. */
export const articlesByDate = (): Article[] =>
  [...articles].sort((a, b) => (a.date < b.date ? 1 : -1));

export const findArticle = (slug: string): Article | undefined =>
  articles.find((a) => a.slug === slug);

/** Сколько читать — считается, а не пишется руками. 180 слов в минуту. */
export function readingMinutes(article: Article): number {
  const words = [article.lead, ...article.blocks.map((b) => b.text)]
    .join(' ')
    .trim()
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 180));
}
