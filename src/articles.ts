export const showBlog = articles.length > 0;

/** Свежие сверху: читателю и поисковику интересно новое. */
export const articlesByDate = (): Article[] =>
  [...articles].sort((a, b) => (a.date < b.date ? 1 : -1));

export const findArticle = (slug: string): Article | undefined =>
  articles.find((a) => a.slug === slug);

/** Сколько читать — считается, а не пишется руками. 180 слов в минуту. */
export function readingMinutes(article: Article): number {
  const words = [article.lead, ...article.blocks.map((b) => b.text)]
    .join(' ')
    .trim()
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 180));
}
